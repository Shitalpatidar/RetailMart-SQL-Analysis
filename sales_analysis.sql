#1	What is the total sales revenue generated by RetailMart?
-- YoY Growth = (1998 Sales − 1997 Sales) / 1997 Sales × 100
select round(sum(p.product_retail_price * t.quantity),2) as total_sales_revenue
from products p
join transactions t
on p.product_id = t.product_id;
/*RetailMart generated $1,764,546.44 in total sales revenue across 1997 and 1998.*/
#2	How does sales revenue change year-over-year (1997 vs 1998)?
with yearly_sale as (select year(t.transactions_date) as sales_year,
round(sum(p.product_retail_price * t.quantity),2) as total_sales_revenue
from products p
join transactions t
on p.product_id = t.product_id
group by year(t.transactions_date)
order by sales_year desc)
                             -- 1997: LAG(total_sales) = NULL because there is no previous year in our data → so no YoY growth can be calculated.
						     -- 1998: total_sales = 1998 sales (current year) and LAG(total_sales) = 1997 sales (previous year).
select sales_year,
       total_sales_revenue,
       round((total_sales_revenue - lag(total_sales_revenue) over(order by sales_year))
          / (lag(total_sales_revenue) over(order by sales_year))*100,2) as yoy_growth_percentage
from yearly_sale
order by sales_year;

/*RetailMart generated $565,238.13 in sales in 1997.
Sales increased to $1,199,308.31 in 1998.
This represents a 112.18% year-over-year growth, meaning sales more than doubled in 1998.
The absolute increase in revenue was approximately $634,070.18.
This indicates a strong improvement in RetailMart's sales performance in 1998.*/

