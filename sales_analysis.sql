## 4️ Which month had the highest sales and which month had the lowest sales across 1997–1998?

WITH monthly_sales AS (
    SELECT
        YEAR(t.transactions_date) AS sales_year,
        MONTH(t.transactions_date) AS sales_month,
        ROUND(SUM(p.product_retail_price * t.quantity), 2) AS total_sales
    FROM transactions AS t
    JOIN products AS p
        ON t.product_id = p.product_id
    GROUP BY
        YEAR(t.transactions_date),
        MONTH(t.transactions_date)
), -- calculate the total sales by month
ranked_sales AS (
    SELECT
        *,
        RANK() OVER (ORDER BY total_sales DESC) AS highest_rank,
        RANK() OVER (ORDER BY total_sales ASC) AS lowest_rank
    FROM monthly_sales
) -- ranked highest and lowest sales using rank window function

SELECT
    sales_year,
    sales_month,
    total_sales,
    CASE
        WHEN highest_rank = 1 THEN 'Highest'
        WHEN lowest_rank = 1 THEN 'Lowest'          -- give the status to the ranks
    END AS sales_status    
FROM ranked_sales
WHERE highest_rank = 1
   OR lowest_rank = 1
order by sales_year desc;

/*December 1998 was RetailMart's strongest sales month, while October 1997 was the weakest.
 This suggests a significant increase in sales performance over the two-year period, with particularly strong year-end demand.*/
 
