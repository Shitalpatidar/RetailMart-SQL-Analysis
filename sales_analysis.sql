September 1998: highest growth → 131.32% */

## 12. How did the number of units sold change from 1997 to 1998?



WITH yearly_units AS (
    SELECT
        YEAR(t.transactions_date) AS sales_year,
        SUM(t.quantity) AS total_units_sold             -- Calculate units sold by year
    FROM transactions AS t
    GROUP BY YEAR(t.transactions_date)
),

unit_growth AS (
    SELECT
        sales_year,
        total_units_sold,                                  -- Calculate YoY unit growth
        LAG(total_units_sold) OVER (
            ORDER BY sales_year
        ) AS previous_year_units
    FROM yearly_units
)

SELECT
    sales_year,
    total_units_sold,
    previous_year_units,
    ROUND(
        (total_units_sold - previous_year_units)
        / previous_year_units * 100,
        2
    ) AS yoy_unit_growth_percentage
FROM unit_growth
WHERE sales_year = 1998
  AND previous_year_units IS NOT NULL;
  
/*Units sold increased from 266,773 in 1997 to 566,716 in 1998, representing 112.42% growth.
 However, 1998 contains substantially more transaction records than 1997, so the increase may partly reflect differences in data coverage/volume.
 Therefore, the result should be interpreted with caution when assessing actual business growth.*/
 
 