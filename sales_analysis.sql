 ## 6️ Which stores experienced the highest sales growth from 1997 to 1998?
 
with yearly_store_sales as (select t.store_id, year(transactions_date) year,
       round(sum(t.quantity * p.product_retail_price) ,2) as total_sales
from transactions as t 
join products as p
on t.product_id = p.product_id
group by t.store_id, year(transactions_date)),  -- calculate yearly store sales


store_growth AS (
    SELECT
        store_id,
        year,
        total_sales,
        LAG(total_sales) OVER (               -- define previous year sales
            PARTITION BY store_id
            ORDER BY year
        ) AS previous_year_sales
    FROM yearly_store_sales
)

SELECT store_id,
        year,
        total_sales,
        previous_year_sales,
        round(
             (
             (total_sales - previous_year_sales)
        / previous_year_sales )* 100,2) as yoy_growth_percentage
        
FROM store_growth
where year = 1998 and previous_year_sales IS NOT NULL
ORDER BY yoy_growth_percentage DESC;


/*Store 16 had the highest YoY growth at 22.60%.
Store 15 ranked second with 20.31% growth.
Store 13, despite being the highest-selling store overall, experienced a 4.63% decline in 1998.
Store 23 also declined by 4.45%.
11 out of 13 stores with comparable data experienced positive growth.
The contrast between Store 13's high revenue and negative growth shows that overall sales and sales growth should be evaluated separately.

business insight: highest sales ≠ highest growth.*/

