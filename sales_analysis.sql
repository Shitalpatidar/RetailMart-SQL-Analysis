## 9. Which stores generate the highest profit?
-- Profit = (Retail Price - Cost Price) × Quantity
SELECT
    t.store_id,
    ROUND(
        SUM(
            (p.product_retail_price - p.product_cost) * t.quantity
        ),
        2
    ) AS total_profit
FROM transactions AS t
JOIN products AS p
    ON t.product_id = p.product_id
GROUP BY t.store_id
ORDER BY total_profit DESC;

/*Store 13 is RetailMart's strongest store in both revenue and profit, but its 4.63% YoY sales decline
 suggests that management should investigate the reason for the recent decline despite its strong profitability.*/
 
 ## 10. Which stores have the highest profit margin?
 
 -- Profit Margin % = (Total Profit / Total Sales) × 100
 
 SELECT
    t.store_id,

    ROUND(
        SUM(t.quantity * p.product_retail_price),
        2
    ) AS total_sales,

    ROUND(
        SUM(
            (p.product_retail_price - p.product_cost) * t.quantity
        ),
        2
    ) AS total_profit,

    ROUND(
        SUM(
            (p.product_retail_price - p.product_cost) * t.quantity
        )
        /
        SUM(t.quantity * p.product_retail_price)
        * 100,
        2
    ) AS profit_margin_percentage

FROM transactions AS t
JOIN products AS p
    ON t.product_id = p.product_id

GROUP BY t.store_id
ORDER BY profit_margin_percentage DESC;

/*Store 5 has the highest margin (59.87%) but the lowest sales, while Store 13 has the highest sales and profit with a 59.69% margin. 
Since margins are almost identical across stores, increasing sales volume appears to be the main driver of higher profit.*/

## 11 Which months had the highest and lowest YoY sales growth?

WITH monthly_sales AS (
    SELECT
        YEAR(t.transactions_date) AS sales_year,
        MONTH(t.transactions_date) AS sales_month,                --    calculate sales by months
        ROUND(
            SUM(p.product_retail_price * t.quantity),
            2
        ) AS total_sales
    FROM transactions AS t
    JOIN products AS p
        ON t.product_id = p.product_id
    GROUP BY
        YEAR(t.transactions_date),
        MONTH(t.transactions_date)
),

monthly_growth AS (
    SELECT
        sales_month,
        sales_year,
        total_sales,                         -- define previous year sale
        LAG(total_sales) OVER (
            PARTITION BY sales_month
            ORDER BY sales_year
        ) AS previous_year_sales
    FROM monthly_sales
)

SELECT
    sales_month,
    total_sales,
    previous_year_sales,
    ROUND(
        (total_sales - previous_year_sales)
        / previous_year_sales * 100,
        2
    ) AS yoy_growth_percentage
FROM monthly_growth
WHERE sales_year = 1998
  AND previous_year_sales IS NOT NULL
ORDER BY yoy_growth_percentage DESC;

/*September 1998 had the highest YoY growth at 131.32%.
March 1998 had the lowest YoY growth at 96.32%.
Even the lowest-growth month, March, still generated 96.32% more sales than March 1997.
All 12 months recorded more than 96% YoY growth, showing very strong and consistent growth.
September's growth was 35 percentage points higher than March.*/

/*One important distinction

