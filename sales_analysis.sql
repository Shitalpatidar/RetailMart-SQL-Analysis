## 8. What are the daily/weekly sales patterns, and which days generate the most sales?

SELECT
    DAYNAME(t.transactions_date) AS day_name,   -- Calculate sales by day of week
    ROUND(
        SUM(t.quantity * p.product_retail_price),
        2
    ) AS total_sales
FROM transactions AS t
